test("plays local video, resumes after reselecting, and switches to MPEG-TS", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto("/")
  const input = page.locator('input[type=file][accept="video/*,.ts,.m2ts,.mts"]:not([webkitdirectory])')
  await input.setInputFiles("tests/fixtures/sample.mp4")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.readyState)).toBeGreaterThanOrEqual(2)
  await page.locator("video").evaluate(async (video: HTMLVideoElement) => { await video.play(); video.currentTime = 5; video.playbackRate = 1.5; video.volume = 0.4; video.pause(); video.dispatchEvent(new Event("timeupdate")) })
  await page.reload()
  await input.setInputFiles("tests/fixtures/sample.mp4")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.currentTime)).toBeGreaterThanOrEqual(4.5)
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.playbackRate)).toBe(1.5)
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.volume)).toBe(0.4)
  await input.setInputFiles("tests/fixtures/sample.ts")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.readyState)).toBeGreaterThanOrEqual(2)
  await page.locator("video").evaluate((video: HTMLVideoElement) => video.play())
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.currentTime)).toBeGreaterThan(0)
  await page.getByRole("button", { name: "移除 sample.ts", exact: true }).click()
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.readyState)).toBeGreaterThanOrEqual(2)
  await input.setInputFiles("tests/fixtures/sample.mp4")
  await expect(page.getByText("1 个视频")).toBeVisible()
  expect(errors).toEqual([])
})

