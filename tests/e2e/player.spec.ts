test("subtitles render, toggle and clear when switching videos", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto("/")
  await page.locator('input[type=file][accept="video/*,.ts,.m2ts,.mts"]:not([webkitdirectory])').first().setInputFiles("tests/fixtures/sample.mp4")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.readyState)).toBeGreaterThanOrEqual(2)
  await page.getByText("字幕、片段循环与快捷键", { exact: true }).click()
  await page.getByLabel("导入字幕", { exact: true }).setInputFiles({ name: "lesson.srt", mimeType: "text/plain", buffer: Buffer.from("1\n00:00:00,000 --> 00:00:11,000\n课程字幕 Hello\n") })
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.textTracks[0]?.cues?.length)).toBe(1)
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.textTracks[0]?.mode)).toBe("showing")
  await page.locator("video").evaluate((video: HTMLVideoElement) => { video.currentTime = 2; video.pause() })
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => (video.textTracks[0]?.activeCues?.[0] as VTTCue)?.text)).toBe("课程字幕 Hello")
  await page.getByRole("button", { name: "隐藏字幕", exact: true }).click()
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.textTracks[0]?.mode)).toBe("disabled")
  await page.getByRole("button", { name: "显示字幕", exact: true }).click()
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.textTracks[0]?.mode)).toBe("showing")
  if (test.info().project.name === "chromium") {
    await page.locator("body").click({ position: { x: 5, y: 5 } })
    await page.keyboard.press("f")
    await expect.poll(() => page.evaluate(() => document.fullscreenElement?.tagName)).toBe("VIDEO")
    await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.textTracks[0]?.mode)).toBe("showing")
    await page.evaluate(() => document.exitFullscreen())
  }
  await page.screenshot({ path: `test-results/study-${test.info().project.name}.png`, fullPage: true })
  await page.getByLabel("导入字幕", { exact: true }).setInputFiles({ name: "bad.srt", mimeType: "text/plain", buffer: Buffer.from("bad") })
  await expect(page.getByRole("alert")).toContainText("字幕格式无效")
  await page.locator('input[type=file][accept="video/*,.ts,.m2ts,.mts"]:not([webkitdirectory])').setInputFiles("tests/fixtures/sample.ts")
  await expect(page.locator("video track")).toHaveCount(0)
  expect(errors).toEqual([])
})

test("A-B loop and shortcuts respect input focus and reset with the video", async ({ page }) => {
  await page.goto("/")
  await page.locator('input[type=file][accept="video/*,.ts,.m2ts,.mts"]:not([webkitdirectory])').first().setInputFiles("tests/fixtures/sample.mp4")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.readyState)).toBeGreaterThanOrEqual(2)
  await page.getByText("字幕、片段循环与快捷键", { exact: true }).click()
  await page.locator("video").evaluate((video: HTMLVideoElement) => { video.pause(); video.currentTime = 2 })
  await page.getByRole("button", { name: "设置 A 点", exact: true }).click()
  await page.getByRole("button", { name: "设置 B 点", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("至少晚 0.5 秒")
  await page.locator("video").evaluate((video: HTMLVideoElement) => { video.currentTime = 4 })
  await page.getByRole("button", { name: "设置 B 点", exact: true }).click()
  await page.locator("video").evaluate((video: HTMLVideoElement) => { video.currentTime = 5; video.dispatchEvent(new Event("timeupdate")) })
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.currentTime)).toBe(2)
  await page.locator("video").evaluate((video: HTMLVideoElement) => { video.currentTime = 3.9; return video.play() })
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.currentTime)).toBeLessThan(3)
  await page.locator("video").evaluate((video: HTMLVideoElement) => { video.pause(); video.currentTime = 12; video.dispatchEvent(new Event("ended")) })
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.currentTime)).toBeLessThan(4)
  await page.locator("video").evaluate((video: HTMLVideoElement) => { video.pause(); video.currentTime = 2 })
  await page.getByRole("button", { name: "清除片段", exact: true }).click()
  await page.getByRole("textbox", { name: "搜索视频或路径" }).fill("k")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.paused)).toBe(true)
  await page.getByRole("textbox", { name: "搜索视频或路径" }).fill("")
  await page.locator("body").click({ position: { x: 5, y: 5 } })
  await page.keyboard.press("ArrowRight")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.currentTime)).toBe(7)
  await page.keyboard.press("k")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.paused)).toBe(false)
  await page.keyboard.press("k")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.paused)).toBe(true)
})


