import { expect, test } from "@playwright/test"

test("invalid media shows recovery UI; playlist persists, searches and deletes", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.route("**/broken.mp4", (route) => route.fulfill({ status: 200, contentType: "video/mp4", body: "not a video" }))
  await page.goto("/")
  await page.getByRole("button", { name: "添加链接", exact: true }).click()
  await page.getByRole("textbox", { name: "视频地址" }).fill("https://example.com/broken.mp4")
  await page.getByRole("button", { name: "确认添加" }).click()
  await expect(page.getByRole("button", { name: "重试", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "重试", exact: true }).click()
  await expect(page.getByRole("alert")).toBeVisible()
  await page.reload()
  await expect(page.getByRole("button", { name: "broken.mp4 在线视频", exact: true })).toBeVisible()
  await page.getByRole("textbox", { name: "搜索视频或路径" }).fill("missing")
  await expect(page.getByRole("button", { name: "移除 broken.mp4" })).toHaveCount(0)
  await page.getByRole("textbox", { name: "搜索视频或路径" }).fill("")
  await page.getByRole("button", { name: "移除 broken.mp4" }).click()
  await expect(page.getByText("0 个视频")).toBeVisible()
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

