test("playlist sorting, undo, search feedback and history management preserve playback", async ({ page }) => {
  await page.goto("/")
  const input = page.locator('input[type=file][accept="video/*,.ts,.m2ts,.mts"]:not([webkitdirectory])')
  await input.setInputFiles(["tests/fixtures/sample.mp4", "tests/fixtures/sample.ts"])
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.readyState)).toBeGreaterThanOrEqual(2)
  await page.locator("video").evaluate((video: HTMLVideoElement) => { video.pause(); video.currentTime = 5; video.dispatchEvent(new Event("pause")) })
  await expect(page.getByText("已看到 00:05", { exact: true })).toBeVisible()
  const source = await page.locator("video").getAttribute("src")
  await page.getByRole("combobox", { name: "排序整个列表" }).selectOption("desc")
  expect(await page.locator("video").getAttribute("src")).toBe(source)
  await expect(page.getByRole("button", { name: "上移 sample.ts", exact: true })).toBeDisabled()
  await page.getByRole("button", { name: "上移 sample.mp4", exact: true }).click()
  await expect(page.getByRole("button", { name: "上移 sample.mp4", exact: true })).toBeDisabled()
  await page.getByRole("button", { name: "移除 sample.ts", exact: true }).click()
  await expect(page.getByText("1 个视频", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "撤销移除", exact: true }).click()
  await expect(page.getByText("2 个视频", { exact: true })).toBeVisible()
  expect(await page.locator("video").getAttribute("src")).toBe(source)
  await page.getByRole("textbox", { name: "搜索视频或路径" }).fill("missing")
  await expect(page.getByText("没有匹配的视频，试试其他名称或路径。", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "清除搜索", exact: true }).click()
  await page.getByRole("button", { name: "清除观看记录", exact: true }).click()
  await page.getByRole("button", { name: "确认清除记录", exact: true }).click()
  await expect(page.getByText("已看到 00:05", { exact: true })).toHaveCount(0)
  await expect(page.getByText("2 个视频", { exact: true })).toBeVisible()
  await page.reload()
  await input.setInputFiles("tests/fixtures/sample.mp4")
  await expect.poll(() => page.locator("video").evaluate((video: HTMLVideoElement) => video.readyState)).toBeGreaterThanOrEqual(2)
  expect(await page.locator("video").evaluate((video: HTMLVideoElement) => video.currentTime)).toBeLessThan(3)
  await page.screenshot({ path: `test-results/playlist-${test.info().project.name}.png`, fullPage: true })
})
